export function useCentralWords() {
  const { i18n } = useTranslation();
  return (i18n.language ?? "pt").toLowerCase().startsWith("pt") ? pt : en;
}

export const BRAIN_NAMES: Record<string, string> = {
  model: "API",
  claude_code: "Claude Code",
  codex: "Codex",
  cursor: "Cursor",
  opencode: "OpenCode",
  grok: "Grok",
  antigravity: "Antigravity",
};

export function setupLine(
  a: { brain: string; model: string | null; effort: string | null },
  w: ReturnType<typeof useCentralWords>,
) {
  return [
    BRAIN_NAMES[a.brain] ?? a.brain,
    a.model && a.model !== "auto" ? a.model : w.auto,
    a.effort && a.effort !== "auto" ? `${w.effort} ${a.effort}` : null,
  ]
    .filter(Boolean)
    .join(" · ");
}
